-- PhishShield AI database schema (reference).
-- The Spring Boot backend creates these tables automatically (spring.jpa.hibernate.ddl-auto=update),
-- so you do NOT need to run this file. It documents the structure and works on H2 and PostgreSQL.

CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(80)  NOT NULL,
    email         VARCHAR(160) NOT NULL UNIQUE,
    password_hash VARCHAR(200) NOT NULL,          -- PBKDF2-HMAC-SHA256, never the plain password
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_sessions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  VARCHAR(64) NOT NULL UNIQUE,      -- SHA-256 of the login token
    user_id     BIGINT      NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS scans (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL,       -- scans belong to the signed-in user
    scan_type       VARCHAR(16)   NOT NULL,       -- MESSAGE or URL
    input_text      VARCHAR(6000) NOT NULL,
    risk_score      INTEGER       NOT NULL,       -- 0 to 100
    risk_level      VARCHAR(16)   NOT NULL,       -- LOW, MEDIUM, HIGH, CRITICAL
    indicators      VARCHAR(60000) NOT NULL,      -- JSON array of indicator objects
    explanation     VARCHAR(2000) NOT NULL,
    recommendations VARCHAR(20000) NOT NULL,      -- JSON array of strings
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_scans_user_created ON scans (user_id, created_at);
